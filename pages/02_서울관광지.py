# 5. 서울 지도
# =====================================

st.divider()
st.header("📍 서울 관광지도")

view_state = pdk.ViewState(
    latitude=37.5665,
    longitude=126.9850,
    zoom=11,
    pitch=0
)

marker_layer = pdk.Layer(
    "ScatterplotLayer",
    data=df,
    get_position="[경도, 위도]",
    get_radius=180,
    get_fill_color=[220, 55, 55, 220],
    get_line_color=[255, 255, 255],
    line_width_min_pixels=2,
    pickable=True,
    auto_highlight=True
)

text_layer = pdk.Layer(
    "TextLayer",
    data=df,
    get_position="[경도, 위도]",
    get_text="순위",
    get_size=16,
    get_color=[25, 25, 25, 255],
    get_alignment_baseline="bottom",
    get_pixel_offset=[0, -12],
    get_text_anchor="middle",
    pickable=True
)

tooltip = {
    "html": """
        <b>{순위}위. {관광지}</b><br/>
        {영문명}<br/>
        {설명}
    """,
    "style": {
        "backgroundColor": "#222222",
        "color": "white"
    }
}

deck = pdk.Deck(
    layers=[marker_layer, text_layer],
    initial_view_state=view_state,
    tooltip=tooltip,
    map_style="light"
)

st.pydeck_chart(
    deck,
    use_container_width=True
)

st.caption(
    "🔴 지도 위의 숫자는 관광지 순위입니다. "
    "마커에 마우스를 올리면 관광지 정보를 볼 수 있어요."
)

